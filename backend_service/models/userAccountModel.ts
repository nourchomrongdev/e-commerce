const { DataTypes } = require("sequelize");
const sequelize = require("./database");

module.exports = sequelize?.define("UserAccount", {
  UserId: { type: DataTypes.INTEGER, primaryKey: true, autoIncrement: true, field: "UserId" },
  UUID: { type: DataTypes.UUID, unique: true, field: "UUID" },
  UserInfoId: { type: DataTypes.INTEGER, allowNull: false, unique: true, field: "UserInfoId" },
  Username: { type: DataTypes.STRING(255), unique: true, field: "Username" },
  PasswordHash: { type: DataTypes.STRING(255), field: "PasswordHash" },
  ResetOtpHash: { type: DataTypes.STRING(64), field: "ResetOtpHash" },
  ResetOtpExpiresAt: { type: DataTypes.DATE, field: "ResetOtpExpiresAt" },
  EmailVerifiedAt: { type: DataTypes.DATE, field: "EmailVerifiedAt" },
  EmailVerificationOtpHash: { type: DataTypes.STRING(64), field: "EmailVerificationOtpHash" },
  EmailVerificationOtpExpiresAt: { type: DataTypes.DATE, field: "EmailVerificationOtpExpiresAt" },
  EmailVerificationOtpRequestedAt: { type: DataTypes.DATE, field: "EmailVerificationOtpRequestedAt" },
  EmailVerificationAttempts: { type: DataTypes.SMALLINT, allowNull: false, defaultValue: 0, field: "EmailVerificationAttempts" },
  RecoveryEmail: { type: DataTypes.STRING(255), field: "RecoveryEmail" },
  RecoveryEmailVerifiedAt: { type: DataTypes.DATE, field: "RecoveryEmailVerifiedAt" },
  RecoveryEmailPending: { type: DataTypes.STRING(255), field: "RecoveryEmailPending" },
  RecoveryEmailVerificationOtpHash: { type: DataTypes.STRING(64), field: "RecoveryEmailVerificationOtpHash" },
  RecoveryEmailVerificationOtpExpiresAt: { type: DataTypes.DATE, field: "RecoveryEmailVerificationOtpExpiresAt" },
  RecoveryEmailVerificationOtpRequestedAt: { type: DataTypes.DATE, field: "RecoveryEmailVerificationOtpRequestedAt" },
  RecoveryEmailVerificationAttempts: { type: DataTypes.SMALLINT, allowNull: false, defaultValue: 0, field: "RecoveryEmailVerificationAttempts" },
  RoleId: { type: DataTypes.INTEGER, allowNull: false, field: "RoleId" },
  Status: { type: DataTypes.ENUM("active", "inactive", "suspended", "banned"), allowNull: false, field: "Status" },
  SuspensionMessage: { type: DataTypes.TEXT, field: "SuspensionMessage" },
  SuspensionStartsAt: { type: DataTypes.DATE, field: "SuspensionStartsAt" },
  SuspendedUntil: { type: DataTypes.DATE, field: "SuspendedUntil" },
  CreatedAt: { type: DataTypes.DATE, field: "CreatedAt" },
  UpdatedAt: { type: DataTypes.DATE, field: "UpdatedAt" },
}, { tableName: "UserAccounts", timestamps: false });
